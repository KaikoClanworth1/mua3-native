"""Writes the icons of gen.py as src/core/hle/prompt_art_data.cpp: one LZ4-block-format blob of RGBA8 pixels
(the 64 x 64 icons one after another, then the small keys) and the tables that say which icon is where."""
import os

import numpy as np


def lz4_block(data, step):
    """LZ4 block format, greedy. `step`: a distance worth trying first (one icon back: most icons share their body)."""
    n = len(data)
    out = bytearray()
    table = {}
    i = anchor = 0

    def emit(lit_from, lit_to, off, mlen):
        ll = lit_to - lit_from
        ml = mlen - 4 if mlen else 0
        out.append((min(ll, 15) << 4) | min(ml, 15))
        if ll >= 15:
            r = ll - 15
            while r >= 255:
                out.append(255)
                r -= 255
            out.append(r)
        out.extend(data[lit_from:lit_to])
        if mlen:
            out.append(off & 255)
            out.append(off >> 8)
            if ml >= 15:
                r = ml - 15
                while r >= 255:
                    out.append(255)
                    r -= 255
                out.append(r)

    def match_len(a, b):
        m = 0
        while b + m < n:
            k = min(256, n - b - m)
            if data[a + m:a + m + k] == data[b + m:b + m + k]:
                m += k
                continue
            while data[a + m] == data[b + m]:
                m += 1
            break
        return m

    while i + 4 <= n:
        key = data[i:i + 4]
        best, boff = 0, 0
        for cand in (i - step, table.get(key, -1)):
            if cand >= 0 and 0 < i - cand <= 65535 and data[cand:cand + 4] == key:
                m = match_len(cand, i)
                if m > best:
                    best, boff = m, i - cand
        table[key] = i
        if best >= 4:
            emit(anchor, i, boff, best)
            for j in range(i + 1, min(i + best, n - 4), 97):
                table[data[j:j + 4]] = j
            i += best
            anchor = i
        else:
            i += 1
    emit(anchor, n, 0, 0)
    return bytes(out)


def lz4_unpack(src, size):
    out = bytearray()
    i = 0
    while i < len(src):
        tok = src[i]
        i += 1
        ll = tok >> 4
        if ll == 15:
            while True:
                b = src[i]
                i += 1
                ll += b
                if b != 255:
                    break
        out += src[i:i + ll]
        i += ll
        if i >= len(src):
            break
        off = src[i] | (src[i + 1] << 8)
        i += 2
        ml = tok & 15
        if ml == 15:
            while True:
                b = src[i]
                i += 1
                ml += b
                if b != 255:
                    break
        ml += 4
        for _ in range(ml):
            out.append(out[-off])
    assert len(out) == size
    return bytes(out)


def write(path, icons, minis, mini_box, spots):
    names = sorted(icons)  # "x" then "x/hold" or "x_hold" stay neighbours
    raw = bytearray()
    for nm in names:
        assert icons[nm].shape == (64, 64, 4)
        raw += icons[nm].tobytes()
    icon_bytes = len(raw)
    x0, y0, x1, y1 = mini_box
    mw, mh = x1 - x0, y1 - y0
    mini_usages = sorted(minis)
    for u in mini_usages:
        for t in minis[u]:
            assert t.shape == (mh, mw, 4)
            raw += t.tobytes()
    raw = bytes(raw)
    blob = lz4_block(raw, 64 * 64 * 4)
    assert lz4_unpack(blob, len(raw)) == raw
    index = {nm: i for i, nm in enumerate(names)}

    L = []
    L.append('// GENERATED by scripts/prompt_art/gen.py - do not edit. Original art drawn by that script (see prompt_art.h).')
    L.append('#include "core/hle/prompt_art_data.h"')
    L.append('')
    L.append('namespace hle::prompt_art::data {')
    L.append('')
    L.append('const u32 kRawSize = %d, kIconCount = %d, kPackedSize = %d;' % (len(raw), len(names), len(blob)))
    L.append('const u32 kMiniOffset = %d, kMiniW = %d, kMiniH = %d, kMiniCount = %d;' % (icon_bytes, mw, mh, len(mini_usages)))
    bx, by = spots['d']
    pos = []
    for d in 'uldr':
        pos.append('{%d, %d}' % (int(round(spots[d][0] - bx)) + x0, int(round(spots[d][1] - by)) + y0))
    L.append('// where the small keys of a cluster go (up, left, down, right): the top left of each tile')
    L.append('const MiniSpot kMiniSpots[4] = {%s};' % ', '.join(pos))
    L.append('// small keys by USB HID usage, in tile order (each: the tile, then its "hold" tile)')
    L.append('const u16 kMiniUsages[] = {%s};' % ', '.join(str(u) for u in mini_usages))
    keys = sorted(int(nm.split('/')[1]) for nm in names if nm.startswith('key/') and nm.count('/') == 1)
    L.append('// keycaps by USB HID usage: {usage, icon} ("hold" is the icon after it)')
    L.append('const KeyIcon kKeys[] = {%s};' % ', '.join('{%d, %d}' % (u, index['key/%d' % u]) for u in keys))
    L.append('const u32 kKeyCount = %d;' % len(keys))
    for u in keys:
        assert index['key/%d/hold' % u] == index['key/%d' % u] + 1
    mice = sorted(int(nm.split('/')[1]) for nm in names if nm.startswith('mouse/') and nm.count('/') == 1)
    assert mice == list(range(len(mice)))
    for m in mice:
        assert index['mouse/%d/hold' % m] == index['mouse/%d' % m] + 1
    L.append('// mouse icons by number (0 move, 1 left, 2 middle, 3 right, 4 back, 5 forward, 6 wheel up, 7 wheel down)')
    L.append('const u16 kMouse[] = {%s};' % ', '.join(str(index['mouse/%d' % m]) for m in mice))
    L.append('const u32 kMouseCount = %d;' % len(mice))
    named = [nm for nm in names if nm.split('/')[0] in ('xbox', 'ps', 'pad')]
    L.append('// pad icons by name')
    L.append('const NamedIcon kNamed[] = {')
    for nm in named:
        L.append('    {"%s", %d},' % (nm, index[nm]))
    L.append('};')
    L.append('const u32 kNamedCount = %d;' % len(named))
    L.append('')
    L.append('const u8 kPacked[] = {')
    for i in range(0, len(blob), 40):
        L.append(','.join(str(b) for b in blob[i:i + 40]) + ',')
    L.append('};')
    L.append('')
    L.append('} // namespace hle::prompt_art::data')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(L) + '\n')
    print('%s: %d icons + %d small keys, %d -> %d bytes packed' % (os.path.normpath(path), len(names), len(mini_usages), len(raw), len(blob)))
